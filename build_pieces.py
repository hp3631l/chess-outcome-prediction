"""
Build-time asset step: fetch the standard Wikipedia/Cburnett chess piece PNGs
and vectorise them into inline SVG paths.

Why vectorise instead of shipping the PNGs?
  The source art is 80x80 raster. Inlined as PNG the pieces go soft on any
  high-DPI screen. Tracing the silhouette to a path keeps the app a single
  self-contained file AND stays crisp at every board size. It also removes the
  last hard dependency on an external chess-piece CDN, which is what made the
  first version of this UI render blank when the CDN was unreachable.

Run:  python build_pieces.py
Out:  pieces.py  ->  PIECES = {"wK": "<path .../>", ...}

Artwork: Wikipedia chess pieces by Cburnett, CC BY-SA 3.0.
Attribution is emitted alongside the data and printed at the end of the report
build.
"""
import base64
import io
import os
import sys
import urllib.request

import numpy as np
from PIL import Image
from skimage import measure
from skimage.morphology import binary_closing, remove_small_holes

SRC = "https://cdn.jsdelivr.net/npm/chessboardjs@0.0.1/www/img/chesspieces/wikipedia/{}.png"
NAMES = ["wK", "wQ", "wR", "wB", "wN", "wP", "bK", "bQ", "bR", "bB", "bN", "bP"]

# viewBox the traced geometry is expressed in (matches the 80x80 source)
VIEW = 80.0


def rdp(points, epsilon):
    """Ramer-Douglas-Peucker simplification, iterative (no recursion limit)."""
    if len(points) < 3:
        return points
    keep = np.zeros(len(points), dtype=bool)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    pts = points.astype(float)
    while stack:
        i, j = stack.pop()
        if j <= i + 1:
            continue
        p0, p1 = pts[i], pts[j]
        d = p1 - p0
        nrm = np.hypot(*d)
        seg = pts[i + 1:j]
        if nrm < 1e-9:
            dist = np.hypot(seg[:, 0] - p0[0], seg[:, 1] - p0[1])
        else:
            dist = np.abs(d[0] * (p0[1] - seg[:, 1]) - (p0[0] - seg[:, 0]) * d[1]) / nrm
        k = int(np.argmax(dist))
        if dist[k] > epsilon:
            keep[i + 1 + k] = True
            stack.append((i, i + 1 + k))
            stack.append((i + 1 + k, j))
    return pts[keep]


def contours_to_path(mask, epsilon=0.55, min_area=6.0):
    """
    Trace the filled silhouette into a single SVG path using even-odd fill.
    Holes (the gaps between a piece's limbs) become inner subpaths, which
    even-odd renders correctly without needing fill-rule gymnastics.
    """
    closed = binary_closing(mask, footprint=np.ones((3, 3)))
    closed = remove_small_holes(closed, area_threshold=4)
    found = measure.find_contours(closed.astype(float), 0.5)

    parts = []
    for c in found:
        if abs(measure.regionprops(measure.label(c.astype(int)))[0].area) if False else False:
            continue
        c = rdp(c, epsilon)
        if len(c) < 3:
            continue
        # find_contours returns (row, col); SVG wants (x, y) => col first.
        pts = [(float(y), float(x)) for x, y in c]
        # drop points the simplifier left nearly collinear
        parts.append("M" + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")

    if not parts:
        return ""
    return "".join(parts)


def build():
    out = {}
    for name in NAMES:
        url = SRC.format(name)
        req = urllib.request.Request(url, headers={"User-Agent": "miniproject/1.0 (educational)"})
        raw = urllib.request.urlopen(req, timeout=30).read()
        img = Image.open(io.BytesIO(raw)).convert("RGBA")
        # The white pieces are drawn dark-on-transparent, black pieces
        # light-on-transparent. Either way the ALPHA channel is the silhouette,
        # which is all we need -- colour is applied at render time.
        alpha = np.array(img)[:, :, 3]
        # supersample the mask so the traced edge is smooth
        big = np.array(img.resize((int(VIEW * 2), int(VIEW * 2)), Image.LANCZOS))[:, :, 3]
        mask = big > 96

        d = contours_to_path(mask, epsilon=0.9)
        coverage = mask.mean()
        out[name] = d
        print(f"  {name}: {len(d):6d} chars  coverage={coverage:5.1%}")

    lines = [
        '"""Chess piece geometry, generated by build_pieces.py -- do not hand-edit.',
        "",
        "Artwork: Wikipedia chess pieces by Cburnett (CC BY-SA 3.0), fetched as",
        "80x80 PNGs from the chessboardjs package and traced to SVG paths.",
        '"""',
        "",
        "VIEWBOX = 160  # traced at 2x the 80px source, then halved on emit",
        "",
        "PIECES = {",
    ]
    for k in NAMES:
        lines.append(f'    "{k}": "{out[k]}",')
    lines.append("}")
    lines.append("")
    lines.append("ATTRIBUTION = (")
    lines.append('    "Chess piece artwork: Wikipedia chess pieces by Cburnett, CC BY-SA 3.0."')
    lines.append(")")
    lines.append("")
    with open("pieces.py", "w") as f:
        f.write("\n".join(lines))
    print(f"\nwrote pieces.py ({os.path.getsize('pieces.py')/1024:.1f} KB)")


if __name__ == "__main__":
    build()
